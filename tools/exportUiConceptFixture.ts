/** Export reproducible design snapshots. Never reads/writes browser saves or changes game rules. */
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createInitialStats } from '../storage/saveStore';
import { runGameTurn } from '../engine/gameEngine';
import { getActionPreview } from '../engine/actionPreview';
import { CHAPTERS, isShortChapter } from '../data/chapters';
import { chapterTactics } from '../data/tactics';
import { formatCampaignDate } from '../engine/time';
import { getOperationIntel } from '../engine/battlefield';
import type { GameStats, ChapterId } from '../types';

const root=path.resolve('design/ui-concepts');
fs.mkdirSync(root,{recursive:true});
function snapshot(chapterId:ChapterId,field:boolean){
  let stats=createInitialStats(19371115,chapterId,null);
  const history:{command:string;text:string}[]=[];
  const commands=chapterId==='sihang'&&field?['start_game','加固一楼入口','休息整顿']:['start_game'];
  let intel='';
  for(const command of commands){
    const result=runGameTurn(stats,command);
    stats={...stats,...result.updatedStats};
    history.push({command,text:result.narrative});
    intel=result.enemyIntel??intel;
  }
  const readOnlyBefore=JSON.stringify(stats);
  const actions=isShortChapter(stats)
    ? chapterId==='street'?[['侦察','侦察路线'],['搜救','搜救街巷'],['护送','护送民众']]:[['压制','压制射击'],['加固','加固桥头'],['轮换','轮换掩护']]
    :[['加固',`加固${stats.location}`],['侦察','侦察敌情'],['搜寻','搜寻物资'],['救治','治疗伤员'],['休息','休息整顿']];
  const previews=actions.map(([label,command])=>{
    const preview=getActionPreview(stats,command);
    const tutorialBlocked=chapterId==='sihang'&&stats.tutorialStep===1&&label!=='加固';
    return {label,command,preview,tutorialBlocked};
  });
  if(readOnlyBefore!==JSON.stringify(stats))throw new Error('Preview mutated the exported state');
  const combatReady=stats.soldiers+stats.hmgSquads.filter(s=>s.status==='active').reduce((n,s)=>n+s.count,0);
  const dialogue=field&&chapterId==='sihang'?runGameTurn(structuredClone(stats),'我有点害怕').narrative:null;
  if(field&&chapterId==='sihang')intel=getOperationIntel(stats.enemyOperation);
  const {rngState:_,enemyOperation,...visibleStats}=stats;
  const visibleOperation=enemyOperation?{turnsRemaining:enemyOperation.turnsRemaining,revealed:enemyOperation.revealed,...(enemyOperation.revealed?{target:enemyOperation.target}:{})}:null;
  return {stats:{...visibleStats,enemyOperation:visibleOperation},combatReady,history,dialogue,intel,date:formatCampaignDate(stats.day),previews,sourceCommands:commands,stateHash:createHash('sha256').update(JSON.stringify(stats)).digest('hex')};
}
const data={
  sourceVersion:'3.7.0',sourceCommit:'9d6a7fe',seed:19371115,
  source:'Snapshots generated by existing local engine; controls only preview, never execute orders.',
  chapters:CHAPTERS.map(chapter=>({...chapter,tactics:chapterTactics(chapter.id),openingSample:snapshot(chapter.id,false),fieldSample:snapshot(chapter.id,true)})),
};
fs.writeFileSync(path.join(root,'fixture.json'),JSON.stringify(data,null,2)+'\n');
